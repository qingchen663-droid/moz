def _index() -> Dict[str, List[str]]:
    """词 → 同组其他词。组心也能被反查（同组内互相扩展）。"""
    lookup: Dict[str, List[str]] = {}
    for group in SYNONYM_GROUPS:
        for word in group:
            others = lookup.setdefault(word, [])
            for other in group:
                if other != word and other not in others:
                    others.append(other)
    return lookup


_WORD_TO_SYNONYMS = _index()


def expand(tokens) -> Dict[str, float]:
    """给一组查询词元，返回「新增的同义写法 → 权重」。

    只返回原集合里没有的词；同一个词被多组命中时取最大权重。
    """
    src = set(tokens)
    out: Dict[str, float] = {}
    for token in src:
        for synonym in _WORD_TO_SYNONYMS.get(token, ()):
            if synonym in src:
                continue
            if synonym not in out and len(out) >= MAX_EXPANSIONS:
                return out
            out[synonym] = max(out.get(synonym, 0.0), EXPAND_WEIGHT)
    return out
