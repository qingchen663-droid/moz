"""中文同义词组（查询侧扩展用）。

形态参考确定性白箱检索路线：每组一个组心，扩展词带统一权重；
不做任何网络调用，不进模型——一次对话的查询扩展成本是本地查表。

口径要说清：这张表只覆盖陪伴/日常对话里高频的"同一件事换个说法"，
不是通用词库。表里没有的组合，扩展不会凭空出现，也不会假装存在。
"""
import os
from typing import Dict, List

ENABLED = os.environ.get("MOZ_SYNONYM", "1") != "0"
EXPAND_WEIGHT = float(os.environ.get("MOZ_SYNONYM_WEIGHT", "0.35"))
MAX_EXPANSIONS = int(os.environ.get("MOZ_SYNONYM_MAX", "24"))

# 每组第一个是组心；组内互为同义（写法尽量保持 2 字以上，方便与二元组词元对齐）
